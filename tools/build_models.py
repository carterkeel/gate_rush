"""Build src/modelData.ts (static parts the game merges at load) from the baked Kenney Mini Dungeon models.
Run tools/bake.py first (it writes /tmp/baked_raw.json). Models: Kenney, CC0 (https://kenney.nl)."""
import base64, math, struct, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from process import *

S = 1.5  # model height 0.8 -> 1.2 units, same as the old block soldier
H = 'character-human:holding-right:0.2'
O = 'character-orc:holding-right:0.2'
SW = 'weapon-sword:none:0'; SP = 'weapon-spear:none:0'; SH = 'shield-round:none:0'
HAND = (-0.2, 0.2, 0.2)

def redden(parts):
    """Enemy orcs: swap R and G on green-skinned vertices so they read as hostile red."""
    for m in parts:
        c = m['col']
        for i in range(0, len(c), 3):
            r, g, b = c[i:i+3]
            if g > r * 1.25 and g > b * 1.1:
                c[i], c[i+1], c[i+2] = min(1, g * 1.15), r * 0.9, b * 0.45
    return parts

def neutralize(parts):
    """Human hair/boots/gloves are orange-brown (they vanish against the dirt track): make them neutral light grey so
    each skin's tint colours them (helmet-like team colour)."""
    for m in parts:
        c = m['col']
        for i in range(0, len(c), 3):
            r, g, b = c[i:i+3]
            if r > 0.45 and g < 0.3 and b < 0.15:
                c[i], c[i+1], c[i+2] = 0.72, 0.74, 0.8
    return parts

PARTS = {
    'human': neutralize(part(H, S)),
    'orc': part(O, S),
    'orcRed': redden(part(O, S)),
    'sword': part(SW, S, offset=HAND),
    'spear': part(SP, S, offset=HAND),
    'shield': part(SH, S, offset=(0.27, 0.2, 0.0), rot=(0, math.pi / 2, 0)),
}

def b64(buf): return base64.b64encode(buf).decode()
out = ['// GENERATED by tools/build_models.py from Kenney "Mini Dungeon" (CC0, https://kenney.nl). Do not edit.',
       'export interface PartData { pos: string; nor: string; col: string; idx: string }',
       'export const PARTS: Record<string, PartData> = {']
tot = 0
for name, meshes in PARTS.items():
    m = merge(meshes)
    pos = struct.pack('<%df' % len(m['pos']), *[round(v, 4) for v in m['pos']])
    nor = struct.pack('<%db' % len(m['nor']), *[max(-127, min(127, round(v * 127))) for v in m['nor']])
    col = struct.pack('<%dB' % len(m['col']), *[max(0, min(255, round(v * 255))) for v in m['col']])
    idx = struct.pack('<%dH' % len(m['idx']), *m['idx'])
    tot += len(pos) + len(nor) + len(col) + len(idx)
    out.append(f"  {name}: {{ pos: '{b64(pos)}', nor: '{b64(nor)}', col: '{b64(col)}', idx: '{b64(idx)}' }},")
    print(name, 'verts', len(m['pos']) // 3, 'tris', len(m['idx']) // 3)
out.append('};')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'modelData.ts'), 'w').write('\n'.join(out) + '\n')
print('bytes', tot)
import json; json.dump({k: merge(v) for k, v in PARTS.items()}, open('/tmp/parts.json', 'w'))
