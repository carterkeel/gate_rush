import base64, os, subprocess
from playwright.sync_api import sync_playwright
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
subprocess.check_call(['npx','esbuild',os.path.join(root,'tools/skull-page.ts'),'--bundle','--format=iife','--outfile=/tmp/skull-page.js'],cwd=root,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
open('/tmp/skull.html','w').write("<html><body style='margin:0;background:#26304a'><script src='file:///tmp/skull-page.js'></script></body></html>")
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--allow-file-access-from-files'])
    pg=b.new_page(); pg.goto('file:///tmp/skull.html'); pg.wait_for_timeout(300)
    out={}
    for name,boss in (('bone',False),('boss',True)):
        out[name]=pg.evaluate('(b)=>window.render(b)',boss)
        open(f'/tmp/skull_{name}.png','wb').write(base64.b64decode(out[name].split(',')[1]))
    out['player']=pg.evaluate('()=>window.renderPlayer()')
    open('/tmp/player.png','wb').write(base64.b64decode(out['player'].split(',')[1]))
    b.close()
open(os.path.join(root,'src/skullData.ts'),'w').write('// generated by tools/skull.py (own voxel design, public domain)\nexport const SKULL_BONE = %r;\nexport const SKULL_BOSS = %r;\nexport const PLAYER_ICON = %r;\n'%(out['bone'],out['boss'],out['player']))
print({k:len(v) for k,v in out.items()})
